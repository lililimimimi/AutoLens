def import_knowledge():
    """批量导入知识库"""
    print(f"📚 开始导入知识库，共 {len(KNOWLEDGE_DOCS)} 条...")

    collection = get_collection(settings.CHROMA_COLLECTION_KNOWLEDGE)

    # 批量导入
    collection.upsert(
        ids=[doc["id"] for doc in KNOWLEDGE_DOCS],
        documents=[doc["document"] for doc in KNOWLEDGE_DOCS],
        metadatas=[doc["metadata"] for doc in KNOWLEDGE_DOCS],
    )

    total = collection.count()
    print(f"✅ 导入完成！知识库现有 {total} 条数据")


if __name__ == "__main__":
    import_knowledge()